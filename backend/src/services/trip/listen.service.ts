import { Types } from "mongoose";
import { z } from "zod";
import { Listen, LISTEN_EVENTS } from "../../models/listen.model";
import { Trip } from "../../models/trip.model";
import type { Identity } from "../user.service";

const objectId = z.string().regex(/^[a-f0-9]{24}$/i, "Not a valid id");

export const ListenBatchSchema = z.strictObject({
  events: z
    .array(
      z.strictObject({
        id: z.string().trim().min(1).max(100), // generated by the phone; makes resending harmless
        tripId: objectId,
        itemId: objectId,
        event: z.enum(LISTEN_EVENTS),
        at: z.iso.datetime({ offset: true }),
      }),
    )
    .min(1)
    .max(200),
});
export type ListenBatch = z.infer<typeof ListenBatchSchema>;

export interface ListenResult {
  accepted: number;
  rejected: Array<{ id: string; code: "TRIP_NOT_FOUND" | "ITEM_NOT_FOUND" }>;
}

// What the user heard, recorded in batches. Events for trips or items the user doesn't own are rejected one by one.
// Idempotent: (userId, clientEventId) is unique and an already stored event counts as accepted.
export async function recordListens(identity: Identity, batch: ListenBatch): Promise<ListenResult> {
  const tripIds = [...new Set(batch.events.map((e) => e.tripId))];
  const trips = await Trip.find({ _id: { $in: tripIds }, userId: identity.uid }, { "items._id": 1, "items.storyId": 1, "items.placeIds": 1 }).lean();
  const byTrip = new Map(trips.map((t) => [String(t._id), new Map(t.items.map((i) => [String(i._id), i]))]));

  const result: ListenResult = { accepted: 0, rejected: [] };
  const ops = [];
  for (const e of batch.events) {
    const items = byTrip.get(e.tripId);
    if (!items) {
      result.rejected.push({ id: e.id, code: "TRIP_NOT_FOUND" });
      continue;
    }
    const item = items.get(e.itemId);
    if (!item) {
      result.rejected.push({ id: e.id, code: "ITEM_NOT_FOUND" });
      continue;
    }
    ops.push({
      updateOne: {
        filter: { userId: identity.uid, clientEventId: e.id },
        update: {
          $setOnInsert: {
            userId: identity.uid, clientEventId: e.id, tripId: new Types.ObjectId(e.tripId), itemId: new Types.ObjectId(e.itemId), ...(item.storyId ? { storyId: item.storyId } : {}),
            placeIds: item.placeIds, event: e.event, at: new Date(e.at),
          },
        },
        upsert: true,
      },
    });
  }
  // A batch resent while the first request is still writing is safe too: MongoDB retries an upsert that loses the
  // race on the unique (userId, clientEventId) index.
  if (ops.length > 0) await Listen.bulkWrite(ops, { ordered: false });
  result.accepted = ops.length;
  return result;
}
